#!/usr/bin/env python3
"""Tiny local M3U / HLS / MPEG-TS server for Matchday development.

Run:
    python tools/fault-server/server.py --port 8088

Emulator URL:
    http://10.0.2.2:8088/playlist.m3u

Real TV over ADB:
    adb reverse tcp:8088 tcp:8088
    http://127.0.0.1:8088/playlist.m3u

Media is generated by generate_media.sh. The server never contains channels of
its own; this is a synthetic test pattern for development only.
"""
from __future__ import annotations

import argparse
import mimetypes
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MEDIA = ROOT / "media"


def playlist(host: str) -> bytes:
    base = f"http://{host}/live"
    body = f"""#EXTM3U
#EXTINF:-1 tvg-id="matchday.test.hls" tvg-name="Test HLS" tvg-logo="" group-title="Test",Test HLS
{base}/ok.m3u8
#EXTINF:-1 tvg-id="matchday.test.ts" tvg-name="Test MPEG-TS" tvg-logo="" group-title="Test",Test MPEG-TS
{base}/ok.ts
"""
    return body.encode("utf-8")


class Handler(BaseHTTPRequestHandler):
    server_version = "MatchdayFaultServer/0.1"
    protocol_version = "HTTP/1.1"

    def _send_file(self, path: Path, head_only: bool = False) -> None:
        if not path.is_file():
            self.send_error(404, "not found")
            return
        size = path.stat().st_size
        content_type = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
        if path.suffix == ".m3u8":
            content_type = "application/vnd.apple.mpegurl"
        elif path.suffix == ".ts":
            content_type = "video/mp2t"

        # Deliberately ignore Range for the synthetic server. The test clips are small,
        # and full 200 responses keep ffmpeg/mpv from treating partial reads as corrupt.
        self.send_response(200)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(size))
        self.send_header("Accept-Ranges", "none")
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        if head_only:
            return
        with path.open("rb") as fh:
            while True:
                chunk = fh.read(64 * 1024)
                if not chunk:
                    break
                self.wfile.write(chunk)

    def _send_playlist(self, head_only: bool = False) -> None:
        host = self.headers.get("Host") or f"127.0.0.1:{self.server.server_port}"
        data = playlist(host)
        self.send_response(200)
        self.send_header("Content-Type", "audio/x-mpegurl; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        if not head_only:
            self.wfile.write(data)

    def do_GET(self) -> None:  # noqa: N802
        self._route(head_only=False)

    def do_HEAD(self) -> None:  # noqa: N802
        self._route(head_only=True)

    def _route(self, head_only: bool) -> None:
        path = self.path.split("?", 1)[0]
        if path in ("/", "/health"):
            body = b"matchday fault server ok\n"
            self.send_response(200)
            self.send_header("Content-Type", "text/plain; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            if not head_only:
                self.wfile.write(body)
            return
        if path == "/playlist.m3u":
            self._send_playlist(head_only)
            return
        if path.startswith("/live/"):
            self._send_file(MEDIA / Path(path.removeprefix("/live/")).name, head_only)
            return
        self.send_error(404, "not found")

    def log_message(self, fmt: str, *args: object) -> None:
        print(f"{self.address_string()} - {fmt % args}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--port", type=int, default=8088)
    parser.add_argument("--host", default="0.0.0.0")
    args = parser.parse_args()
    if not (MEDIA / "ok.m3u8").is_file():
        raise SystemExit("media missing. Run tools/fault-server/generate_media.sh first.")
    httpd = ThreadingHTTPServer((args.host, args.port), Handler)
    print(f"Matchday test server on http://{args.host}:{args.port}")
    print(f"Emulator playlist: http://10.0.2.2:{args.port}/playlist.m3u")
    httpd.serve_forever()


if __name__ == "__main__":
    main()
